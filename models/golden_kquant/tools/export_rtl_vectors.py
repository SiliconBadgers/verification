#!/usr/bin/env python3
"""Export real-tensor test vectors for the matrix unit RTL (bpu_sa_sram_wrapper_golden_tb).

Writes a SystemVerilog package with a memory image (A, B, scale tables in the wrapper's
SRAM layout), a command list and the expected C of every command, computed by the golden
model's contract mode (golden/hwmode.py). An 8 x 8 tile, K = 2048 (the model's hidden size):

  A    the dequantized token embeddings of 8 real tokens -> INT8, bf16 per 16
  B4   blk.0.ffn_gate.weight output channels 0-7 (q4_K) -> INT4, bf16 per 16
  B8   blk.0.attn_qkv.weight output channels 0-7 (q5_K) -> INT8, bf16 per 16

  0  INT4 block-scaled, K = 2048                    write
  1  INT8 block-scaled, K = 2048                    write
  2  INT4 block-scaled, first half of K             keep (clear, no write)
  3  INT4 block-scaled, second half, continued      write: must equal command 0
  4  INT8 unscaled, K = 2048                        write (exact int32)

The requantization rule is an assumption (golden/hwmode.py docstring).

Usage: python3 tools/export_rtl_vectors.py MODEL.gguf OUT.sv
"""

import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from golden.blocks import dequantize  # noqa: E402
from golden.gguf import GGUF  # noqa: E402
from golden.hwmode import BLOCK_K, requantize, scaled_element, unscaled_element  # noqa: E402

ROWS = COLS = 8
K = 2048
ROW_BYTES = 512
TOKENS = (151644, 872, 9707, 1879, 279, 3681, 13, 198)
W4 = "blk.0.ffn_gate.weight"
W8 = "blk.0.attn_qkv.weight"


def main():
    model, out = sys.argv[1], Path(sys.argv[2])
    g = GGUF(model)
    sha = hashlib.sha256(Path(model).read_bytes()).hexdigest()

    a_float = [dequantize("q6_K", g.read_rows("token_embd.weight", t, 1)) for t in TOKENS]
    a = [requantize(row, 8) for row in a_float]  # per row i: (codes[K], scales[K/16])

    def weights(name, bits):
        t = g.tensors[name]
        cols = [dequantize(t.type_name, g.read_rows(name, j, 1)) for j in range(COLS)]
        return [requantize(c, bits) for c in cols]  # per column j

    b4, b8 = weights(W4, 4), weights(W8, 8)
    G = K // BLOCK_K

    # --- memory image, row-aligned regions -------------------------------------------
    mem = bytearray()

    def region(data):
        start = len(mem)
        mem.extend(data)
        mem.extend(bytes(-len(mem) % ROW_BYTES))
        return start

    a_bytes = bytes(a[i][0][k] & 0xFF for k in range(K) for i in range(ROWS))  # k-major
    b8_bytes = bytes(b8[j][0][k] & 0xFF for k in range(K) for j in range(COLS))  # row-major
    nib = [b4[j][0][k] & 0xF for k in range(K) for j in range(COLS)]  # n = k*Cols + j
    b4_bytes = bytes(nib[n] | (nib[n + 1] << 4) for n in range(0, len(nib), 2))

    def table(scales_of, count):  # entry (g, x) at 2 * (g * count + x), little-endian
        return b"".join(scales_of(x, gg).to_bytes(2, "little") for gg in range(G) for x in range(count))

    a_addr = region(a_bytes)
    b4_addr = region(b4_bytes)
    b8_addr = region(b8_bytes)
    sa_addr = region(table(lambda i, gg: a[i][1][gg], ROWS))
    sb4_addr = region(table(lambda j, gg: b4[j][1][gg], COLS))
    sb8_addr = region(table(lambda j, gg: b8[j][1][gg], COLS))
    c_addrs = [region(bytes(4 * ROWS * COLS)) for _ in range(5)]

    # --- expected C ------------------------------------------------------------------
    def tile(bq, scaled, k0=0, k1=K):
        out_words = []
        for i in range(ROWS):
            for j in range(COLS):
                ac, bc = a[i][0][k0:k1], bq[j][0][k0:k1]
                if scaled:
                    out_words.append(scaled_element(ac, bc, a[i][1][k0 // BLOCK_K : k1 // BLOCK_K],
                                                    bq[j][1][k0 // BLOCK_K : k1 // BLOCK_K]))
                else:
                    out_words.append(unscaled_element(ac, bc))
        return out_words

    c_int4 = tile(b4, True)
    half = K // 2
    hb = half // BLOCK_K
    # k, int4, scaled, clear, write, a, b, sa, sb, c
    cmds = [
        (K, 1, 1, 1, 1, a_addr, b4_addr, sa_addr, sb4_addr, c_addrs[0]),
        (K, 0, 1, 1, 1, a_addr, b8_addr, sa_addr, sb8_addr, c_addrs[1]),
        (half, 1, 1, 1, 0, a_addr, b4_addr, sa_addr, sb4_addr, c_addrs[2]),
        (half, 1, 1, 0, 1, a_addr + half * ROWS, b4_addr + half * COLS // 2,
         sa_addr + 2 * hb * ROWS, sb4_addr + 2 * hb * COLS, c_addrs[3]),
        (K, 0, 0, 1, 1, a_addr, b8_addr, 0, 0, c_addrs[4]),
    ]
    for c in cmds:
        assert all(x % ROW_BYTES == 0 for x in c[5:10]), "addresses must be row-aligned"
    expect = [c_int4, tile(b8, True), [0] * 64, c_int4, tile(b8, False)]

    # --- package ---------------------------------------------------------------------
    rows = len(mem) // ROW_BYTES
    L = []
    L.append("// Generated by SiliconBadgers/verification, models/golden_kquant/tools/"
             "export_rtl_vectors.py.")
    L.append("// Do not edit; regenerate (models/golden_kquant/README.md).")
    L.append(f"// Model: Qwen3.5-2B-Q4_K_M.gguf, sha256 {sha[:16]}..{sha[-8:]}")
    L.append(f"// A: token_embd rows for tokens {', '.join(map(str, TOKENS))}, dequantized,")
    L.append("//    requantized to INT8 with bf16 scales per 16 (assumed rule, golden/hwmode.py)")
    L.append(f"// B: {W4} channels 0-7 -> INT4; {W8} channels 0-7 -> INT8")
    L.append("// Expected C: golden/hwmode.py, the matrix unit's arithmetic contract.")
    L.append("package bpu_sa_golden_vectors_pkg;")
    L.append(f"  localparam int unsigned GV_ROWS = {ROWS};")
    L.append(f"  localparam int unsigned GV_COLS = {COLS};")
    L.append(f"  localparam int unsigned GV_BLOCK_K = {BLOCK_K};")
    L.append(f"  localparam int unsigned GV_ROW_BYTES = {ROW_BYTES};")
    L.append(f"  localparam int unsigned GV_MEM_ROWS = {rows};")
    L.append(f"  localparam int unsigned GV_C_LO = {c_addrs[0]};")
    L.append(f"  localparam int unsigned GV_C_HI = {c_addrs[-1] + ROW_BYTES};")
    L.append(f"  localparam int unsigned GV_COMMANDS = {len(cmds)};")
    L.append("  // k, int4, scaled, clear_acc, write_output, a, b, sa, sb, c addresses")
    L.append("  localparam int unsigned GV_CMD[GV_COMMANDS][10] = '{")
    for n, c in enumerate(cmds):
        L.append("    '{" + ", ".join(str(x) for x in c) + "}" + ("," if n < len(cmds) - 1 else ""))
    L.append("  };")
    L.append("  // Expected C, row-major (element r * GV_COLS + j); unused for keep commands")
    L.append("  localparam logic [31:0] GV_C[GV_COMMANDS][GV_ROWS*GV_COLS] = '{")
    for n, words in enumerate(expect):
        L.append("    '{")
        for p, w in enumerate(words):  # one element per line: Verible's canonical layout
            L.append(f"      32'h{w:08x}" + ("," if p < len(words) - 1 else ""))
        L.append("    }" + ("," if n < len(expect) - 1 else ""))
    L.append("  };")
    L.append("  // Memory image, one SRAM row per entry; byte b of a row is bits [8*b +: 8]")
    L.append("  localparam logic [8*GV_ROW_BYTES-1:0] GV_MEM[GV_MEM_ROWS] = '{")
    for r in range(rows):
        row = mem[r * ROW_BYTES : (r + 1) * ROW_BYTES]
        # 64-bit chunks, most significant first, so a row is one concatenation
        chunks = [int.from_bytes(row[o : o + 8], "little") for o in range(ROW_BYTES - 8, -8, -8)]
        L.append("    {")
        for p, c in enumerate(chunks):
            L.append(f"      64'h{c:016x}" + ("," if p < len(chunks) - 1 else ""))
        L.append("    }" + ("," if r < rows - 1 else ""))
    L.append("  };")
    L.append("endpackage")
    out.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out}: {rows} SRAM rows ({len(mem)} bytes), {len(cmds)} commands")


if __name__ == "__main__":
    main()
