"""Write golden vectors for bpu_sa_output_convert (the matrix unit's output encodings,
docs/compute/matrix_unit_spec.md "Output representations") as a SystemVerilog package.

Expected values come from golden/matrix_v1.py. Cases: every edge the encodings have
(FP16 subnormals, ties and the overflow threshold, INT32 and INT8 saturation and ties,
the full 80-bit INT8 product, NaN and overflow flags, zero, integer extremes), plus random
values over the whole Q23.24 and INT32 ranges with random fractional bits, multipliers
and shifts.

Each vector: scaled, nan, ovf, value (signed: AccW-wrapped integer or Q23.24 code), fmt,
frac, mul, shift, expected (the element in the low ELEMENT_BYTES[fmt] bytes).

Usage: python3 tools/export_convert_vectors.py OUT.sv [--count N] [--seed S]
"""

import argparse
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from golden.hwmode import FX_MAX, FX_MIN  # noqa: E402
from golden.matrix_v1 import FMT_INT8, Native, convert  # noqa: E402

I32_MIN, I32_MAX = -(1 << 31), (1 << 31) - 1


def edge_cases():
    """(Native, fmt, frac, mul, shift) tuples at every boundary."""
    out = []
    fx_values = [0, 1, -1, 3, (1 << 10) - 1, 1 << 10, (1 << 11) + 1, (1 << 11) + 3,
                 (1 << 24) + (1 << 13), (1 << 24) + (1 << 13) + 1, 3 << 23, 5 << 23, -(5 << 23),
                 65504 << 24, (65519 << 24) + (1 << 23), 65520 << 24, FX_MAX, FX_MIN, FX_MAX - 1,
                 FX_MIN + 1, (1 << 47) - (1 << 23), 127 << 24, 128 << 24, -(127 << 24) - (1 << 23)]
    int_values = [0, 1, -1, 2049, 2051, 65504, 65519, 65520, -70000, (1 << 24) + 1, (1 << 24) + 3,
                  I32_MAX, I32_MIN, 127, 128, -128, -127, 3, 5, -5, 1000]
    for v in fx_values:
        x = Native(True, v)
        for fmt in range(5):
            for frac in (0, 7, 24, 31):
                out.append((x, fmt, frac, 1, 24))
        out.append((x, FMT_INT8, 0, 0xFFFFFFFF, 79))
        out.append((x, FMT_INT8, 0, 0xFFFFFFFF, 80))
        out.append((x, FMT_INT8, 0, 0xFFFFFFFF, 127))
        out.append((x, FMT_INT8, 0, 3, 25))
    for v in int_values:
        x = Native(False, v)
        for fmt in range(5):
            for frac in (0, 1, 31):
                out.append((x, fmt, frac, 1, 0))
        out.append((x, FMT_INT8, 0, 1, 1))
        out.append((x, FMT_INT8, 0, 0xFFFFFFFF, 32))
        out.append((x, FMT_INT8, 0, 7, 127))
    for fmt in range(5):
        for ovf, nan, v in ((True, False, FX_MAX), (True, False, FX_MIN), (False, True, 5),
                            (True, True, FX_MIN)):
            out.append((Native(True, v, ovf, nan), fmt, 3, 9, 30))
    return out


def random_cases(rng, count):
    out = []
    for _ in range(count):
        scaled = rng.random() < 0.6
        if scaled:
            v = rng.randrange(FX_MIN, FX_MAX + 1) >> rng.randrange(0, 48)
            r = rng.random()
            x = Native(True, v, ovf=r < 0.03, nan=0.03 <= r < 0.05)
            if x.ovf:
                x = Native(True, FX_MAX if rng.random() < 0.5 else FX_MIN, True, x.nan)
        else:
            v = rng.randrange(I32_MIN, I32_MAX + 1) >> rng.randrange(0, 32)
            x = Native(False, v)
        fmt = rng.randrange(5)
        frac = rng.randrange(32)
        mul = rng.getrandbits(rng.choice((1, 8, 16, 32)))
        shift = rng.randrange(128) if rng.random() < 0.3 else rng.randrange(20, 60)
        out.append((x, fmt, frac, mul, shift))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--count", type=int, default=3000)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    cases = edge_cases() + random_cases(random.Random(args.seed), args.count)
    lines = [
        "// Generated by verification models/golden_kquant/tools/export_convert_vectors.py",
        f"// (--count {args.count} --seed {args.seed}); expected values from golden/matrix_v1.py.",
        "// Do not edit. Fields: scaled, nan, ovf, value (48-bit two's complement), fmt, frac,",
        "// mul, shift, expected element (zero-extended to 32 bits).",
        "package bpu_sa_convert_vectors_pkg;",
        "",
        "  typedef struct packed {",
        "    logic        scaled;",
        "    logic        nan;",
        "    logic        ovf;",
        "    logic [47:0] value;",
        "    logic [2:0]  fmt;",
        "    logic [5:0]  frac;",
        "    logic [31:0] mul;",
        "    logic [6:0]  shift;",
        "    logic [31:0] expected;",
        "  } cv_vector_t;",
        "",
        f"  localparam int unsigned CV_COUNT = {len(cases)};",
        "  localparam cv_vector_t CV_VECTORS[CV_COUNT] = '{",
    ]
    body = []
    for x, fmt, frac, mul, shift in cases:
        exp = convert(x, fmt, frac, mul, shift)
        body.append(f"    '{{1'b{int(x.scaled)}, 1'b{int(x.nan)}, 1'b{int(x.ovf)}, "
                    f"48'h{x.value & ((1 << 48) - 1):012x}, 3'd{fmt}, 6'd{frac}, 32'h{mul:08x}, "
                    f"7'd{shift}, 32'h{exp:08x}}}")
    lines.append(",\n".join(body))
    lines += ["  };", "", "endpackage", ""]
    Path(args.out).write_text("\n".join(lines), newline="\n")
    counts = [sum(1 for c in cases if c[1] == f) for f in range(5)]
    print(f"wrote {len(cases)} vectors to {args.out}; per format {counts}")


if __name__ == "__main__":
    main()
